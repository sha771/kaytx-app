export interface AIAgentIntegration {
  system: string;
  type: 'native' | 'api' | 'webhook' | 'sync';
  status: 'active' | 'pending' | 'planned';
  lastSync?: string;
}

export interface AIAgentMetrics {
  tasksCompleted: number;
  avgResponseTime: string;
  successRate: number;
  customerSatisfaction: number;
  costSavings: string;
  roi: string;
}

export interface AIAgentFeature {
  id: string;
  name: string;
  description: string;
  enabled: boolean;
  configOptions?: Record<string, any>;
}

export interface AIAgent {
  id: string;
  name: string;
  role: string;
  department: string;
  level: 'chief' | 'vp' | 'director' | 'manager' | 'specialist';
  type: 'main_agent' | 'subagent';
  icon: LucideIcon;
  color: string;
  description: string;
  longDescription: string;
  responsibilities: string[];
  capabilities: AIAgentCapability[];
  workflows: AIAgentWorkflow[];
  integrations: AIAgentIntegration[];
  features: AIAgentFeature[];
  metrics: AIAgentMetrics;
  parentId?: string;
  subAgentIds?: string[];
  reportingTo?: string;
  tools: string[];
  kpis: string[];
  slaTargets: {
    responseTime: string;
    resolutionTime: string;
    availability: string;
  };
  autoScale: {
    enabled: boolean;
    minInstances: number;
    maxInstances: number;
    scaleTrigger: string;
  };
  createdAt: string;
  updatedAt: string;
  version: string;
  status: 'active' | 'inactive' | 'maintenance' | 'training';
}

