export const getCoreCapabilitiesProcedure = publicProcedure
  .query(() => {
    const enabledCount = coreCapabilities.filter(c => c.enabled).length;
    const avgPerformance = Math.round(
      coreCapabilities.reduce((acc, c) => acc + c.performance, 0) / coreCapabilities.length
    );
    
    return {
      capabilities: coreCapabilities,
      stats: {
        total: coreCapabilities.length,
        enabled: enabledCount,
        avgPerformance,
        healthScore: avgPerformance,
      },
    };
  });

export const toggleCoreCapabilityProcedure = publicProcedure
  .input(z.object({
    capabilityId: z.string(),
    enabled: z.boolean(),
  }))
  .mutation(({ input }) => {
    console.log(`Toggling core capability ${input.capabilityId} to ${input.enabled ? 'enabled' : 'disabled'}`);
    
    return {
      success: true,
      capabilityId: input.capabilityId,
      enabled: input.enabled,
      message: `Core capability ${input.capabilityId} has been ${input.enabled ? 'enabled' : 'disabled'}`,
      timestamp: new Date().toISOString(),
    };
  });

